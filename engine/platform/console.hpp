#pragma once

namespace vx {

/// 让**本进程所附的控制台**按 **UTF-8** 解释输出（Windows：把控制台输出 / 输入代码页设为 65001）。
///
/// **为什么需要**：工程内所有面向人的字符串都是 **UTF-8**（编译期 `/utf-8`，见根 `CMakeLists.txt`），
/// 而 Windows 控制台默认按**本地 ANSI 代码页**解码（简体中文系统 = 936 / GBK）⇒ 中文日志在终端里显示为
/// **乱码**（UTF-8 字节被当 GBK 解释，看似繁体字）。启动时调一次即可让终端显示正常简体中文。
///
/// **不影响重定向**：输出到文件 / 管道时写入的仍是**原始 UTF-8 字节**，编码设置只作用于"控制台如何解码"。
///
/// 前置条件：在**任何日志之前**调用（本函数自身不产生日志）。无控制台（如 GUI 子系统启动）时**静默忽略**。
/// 非 Windows 平台无需设置（终端本身即 UTF-8）⇒ 空操作。不抛异常、不分配堆内存。
/// 线程约定：只在启动期、任何工作线程启动之前调用一次。
///
/// 返回：设置后**实际生效的控制台输出代码页**（Windows = `GetConsoleOutputCP()`；**0 = 没有附加控制台**
/// 或非 Windows）。**返回值用于让调用方把"是否真的设上了"写进日志**（可判定证据，而不是一句声明）。
[[nodiscard]] unsigned int EnableUtf8ConsoleOutput() noexcept;

}  // namespace vx
